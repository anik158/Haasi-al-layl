/**
 * The 99 Names of Allah (Asmaʾ al-Husna).
 *
 * That Allah has ninety-nine names, and whoever enumerates them enters Paradise, is in Sahih
 * al-Bukhari 2736 and Sahih Muslim 2677. The list itself is the one narrated in Jami' at-Tirmidhi
 * 3507, followed exactly: "Allah" is the first of the ninety-nine, and al-Ahad is not in it (some
 * popular lists add it and drop "Allah"). Its chain is graded da'if, and the screen says so.
 * Meanings are short glosses written for this app; the Bengali, Spanish and Portuguese are owed a
 * review.
 */
data class AllahName(
  val number: Int,
  val arabic: String,
  val transliteration: String,
  val meanings: Map<AppLanguage, String>,
  /** The pronunciation in Bengali script, for reading in Bengali rather than in Latin letters. */
  val transliterationBn: String = "",
  /**
   * Spanish-adapted spelling: Y for ج and J for خ, since a Spanish reader says "j" as the throaty
   * خ, plus accents on long vowels - the convention of Spanish-speaking Muslims (Al-Yabbár,
   * Al-Jáliq). Portuguese keeps the common English-style spelling, which reads well enough there.
   */
  val transliterationEs: String = "",
  /** A short explanation per language, from [ASMA_EXPLANATIONS]. Owed a scholar's review. */
  val explanations: Map<AppLanguage, String> = emptyMap(),
  /** One verse ("59:23") where the name, or the verb it comes from, occurs; null where none does. */
  val quranRef: String? = null
) {
  fun explanation(language: AppLanguage): String =
    explanations[language]?.takeIf { it.isNotBlank() }
      ?: explanations[AppLanguage.ENGLISH].orEmpty()

  /**
   * The pronunciation for [language]: Bengali script in Bengali, Spanish spelling in Spanish, none
   * in Arabic (the Arabic is already the name), and the common Latin spelling otherwise.
   */
  fun pronunciation(language: AppLanguage): String? = when (language) {
    AppLanguage.ARABIC -> null
    AppLanguage.BENGALI -> transliterationBn.ifBlank { transliteration }
    AppLanguage.SPANISH -> transliterationEs.ifBlank { transliteration }
    AppLanguage.ENGLISH, AppLanguage.PORTUGUESE -> transliteration
  }

  fun meaning(language: AppLanguage): String =
    meanings[language]?.takeIf { it.isNotBlank() }
      ?: meanings[AppLanguage.ENGLISH].orEmpty()
}

